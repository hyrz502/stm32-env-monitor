/**
  * @brief  显示字符（6x8）。
  * @param  column: 字符列 0~20; page: 页 0~7
  */
void OLED_ShowChar(uint8_t column, uint8_t page, char ch)
{
  uint8_t x = (uint8_t)(column * 6);
  uint8_t idx;

  if (ch < 32 || ch > 126)
  {
    return;
  }
  if (page > 7 || (x + 6) > 128)
  {
    return;
  }
  idx = (uint8_t)(ch - 32);
  for (uint8_t i = 0; i < 6; i++)
  {
    GRAM[page][x + i] = Font6x8[idx][i];
  }
}

/**
  * @brief  显示字符串（6x8），超宽自动换行。
  */
void OLED_ShowString(uint8_t column, uint8_t page, const char *str)
{
  uint8_t x = (uint8_t)(column * 6);

  while (*str)
  {
    if ((x + 6) > 128)
    {
      x = 0;
      page++;
      if (page > 7)
      {
        return;
      }
    }
    OLED_ShowChar((uint8_t)(x / 6), page, *str);
    x += 6;
    str++;
  }
}

static uint16_t Pow10(uint16_t exp)
{
  uint16_t r = 1;
  while (exp--)
  {
    r *= 10;
  }
  return r;
}

/**
  * @brief  显示无符号整数（定宽，左端补 0）。
  * @param  column: 起始字符列; page: 页; num: 数值; len: 位数
  */
void OLED_ShowNum(uint16_t column, uint16_t page, uint32_t num, uint8_t len)
{
  for (uint8_t i = 0; i < len; i++)
  {
    OLED_ShowChar((uint8_t)(column + i), (uint8_t)page,
                  (char)((num / Pow10((uint16_t)(len - 1 - i))) % 10 + '0'));
  }
}
