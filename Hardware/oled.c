/******************************************************************************
功能：显示字符（6x8）
参数：列（0~20）
参数：上下方向页（0~7）
******************************************************************************/
void OLED_ShowChar(uint8_t column, uint8_t page, char ch)
{
	uint8_t x=column*6;
	if (ch < 32 || ch > 126) return;
	if (page > 7 || x + 6 > 128) return;

	uint8_t idx = ch - 32;
	for (uint8_t i = 0; i < 6; i++)
	{
		GRAM[page][x + i] = OLED_Font6x8[idx][i];
	}
}

/******************************************************************************
功能：显示字符串(6x8)
参数：列（0~20）
参数：上下方向页（0~7）
******************************************************************************/
void OLED_ShowString(uint8_t column, uint8_t page, const char *str)
{
	uint8_t x = column*6;
	while (*str)
	{
		if (x + 6 > 128)
		{
			x = 0;
			page++;
			if (page > 7) return;
		}
		OLED_ShowChar(x/6, page, *str);
		x += 6;
		str++;
	}
}

uint16_t Pow(uint16_t x,uint16_t y)
{
	uint16_t result=1;
	while(y--)
	{
		result*=x;
	}
	return result;
}

/******************************************************************************
功能：显示数字（0~4,294,967,295）(6x8)
参数：列（0~20）
参数：上下方向页（0~7）
******************************************************************************/
void OLED_ShowNum(uint16_t Column,uint16_t Page,uint32_t num,uint8_t len)
{
	
	for(uint8_t i=0;i<len;i++)
	{
		OLED_ShowChar(Column+i,Page,num/(Pow(10,len-1-i))%10+'0');
	}
}

